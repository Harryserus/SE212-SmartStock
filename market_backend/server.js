require("dotenv").config();
const express=require("express");
const cors=require("cors");
const categoryRoutes=require("./routes/categoryRoutes");
const productRoutes=require("./routes/productRoutes");
const inventoryRoutes=require("./routes/inventoryRoutes");
const salesRoutes=require("./routes/salesRoutes");
const managementRoutes=require("./routes/managementRoutes");
const supplierRoutes=require("./routes/supplierRoutes");
const purchaseOrderRoutes=require("./routes/purchaseOrderRoutes");
const supplierIssueRoutes=require("./routes/supplierIssueRoutes");
const employeeRoutes=require("./routes/employeeRoutes");
const productSupplierRoutes=require("./routes/productSupplierRoutes");
const app=express();
app.use(cors());
app.use(express.json());
app.get("/",(req,res)=>res.json({message:"SmartStock API is running"}));
app.use("/api/categories",categoryRoutes);
app.use("/api/products",productRoutes);
app.use("/api/inventory",inventoryRoutes);
app.use("/api/sales",salesRoutes);
app.use("/api/suppliers",supplierRoutes);
app.use("/api/purchase-orders",purchaseOrderRoutes);
app.use("/api/supplier-issues",supplierIssueRoutes);
app.use("/api/employees",employeeRoutes);
app.use("/api/product-suppliers",productSupplierRoutes);
app.use("/api/management",managementRoutes);
app.use((error,req,res,next)=>{
 if(error instanceof SyntaxError&&error.status===400&&"body" in error)return res.status(400).json({error:"Invalid JSON request body"});
 console.error(error);res.status(500).json({error:"Internal server error"});
});
const PORT=process.env.PORT||3000;
app.listen(PORT,()=>console.log(`Server running at http://localhost:${PORT}`));
